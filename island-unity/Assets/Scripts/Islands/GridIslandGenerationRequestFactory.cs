using System;
using System.Collections.Generic;
using UnityEngine;

[DisallowMultipleComponent]
public sealed class GridIslandGenerationRequestFactory :
    IslandGenerationRequestFactoryBase
{
    [Serializable]
    public sealed class FixedIsland
    {
        [SerializeField] private Vector2Int gridPosition;
        [SerializeField] private string stableId;

        public Vector2Int GridPosition => gridPosition;
        public string StableId => stableId;

        public FixedIsland(
            Vector2Int gridPosition,
            string stableId = null)
        {
            this.gridPosition = gridPosition;
            this.stableId = stableId;
        }
    }

    [Header("World Distribution")]
    [Tooltip("Seed used to select occupied cells and derive each island seed.")]
    [SerializeField] private int seed = 8675309;

    [Header("Fixed Cells")]
    [Tooltip("Cells that always contain an island generated by this factory.")]
    [SerializeField] private List<FixedIsland> fixedIslands = new List<FixedIsland>();

    [Header("Unlisted Cells")]
    [Tooltip("Allow cells not listed above to contain procedurally selected islands.")]
    [SerializeField] private bool generateUnlistedCells = true;
    [Range(0f, 1f)] [SerializeField] private float unlistedCellOccupancy = 0.32f;
    [Tooltip("Deterministic parameter variation applied independently to every returned request.")]
    [SerializeField] private IslandParameterVariationSettings parameterVariation =
        new IslandParameterVariationSettings();

    public int FixedIslandCount => fixedIslands.Count;
    public bool GeneratesUnlistedCells => generateUnlistedCells;
    public float UnlistedCellOccupancy => unlistedCellOccupancy;
    public int Seed => seed;

    public override bool HasIsland(Vector2Int islandGridPosition)
    {
        if (FindFixedIsland(islandGridPosition) != null)
        {
            return true;
        }
        if (!generateUnlistedCells)
        {
            return false;
        }
        return IsOccupied(RandomTools.SeedForCell(seed, islandGridPosition));
    }

    public override IslandGenerationRequest CreateIslandGenerationRequest(
        Vector2Int islandGridPosition)
    {
        var randomSeed = RandomTools.SeedForCell(seed, islandGridPosition);
        var fixedIsland = FindFixedIsland(islandGridPosition);
        if (fixedIsland == null && !HasIsland(islandGridPosition))
        {
            return null;
        }

        var profile = CreateProfile();
        profile.Generation.Seed = randomSeed;
        ApplyDeterministicVariation(profile.Generation, randomSeed);
        return CreateRequest(
            randomSeed,
            islandGridPosition,
            profile,
            fixedIsland?.StableId);
    }

    public void Configure(
        int factorySeed,
        bool populateUnlistedCells,
        float unlistedOccupancy)
    {
        seed = factorySeed;
        generateUnlistedCells = populateUnlistedCells;
        unlistedCellOccupancy = Mathf.Clamp01(unlistedOccupancy);
    }

    public void SetFixedIslands(params FixedIsland[] definitions)
    {
        fixedIslands.Clear();
        if (definitions != null)
        {
            fixedIslands.AddRange(definitions);
        }
        ValidateFixedIslands();
    }

    private FixedIsland FindFixedIsland(Vector2Int gridPosition)
    {
        foreach (var fixedIsland in fixedIslands)
        {
            if (fixedIsland != null && fixedIsland.GridPosition == gridPosition)
            {
                return fixedIsland;
            }
        }
        return null;
    }

    private bool IsOccupied(int randomSeed)
    {
        if (unlistedCellOccupancy <= 0f)
        {
            return false;
        }
        if (unlistedCellOccupancy >= 1f)
        {
            return true;
        }
        var hash = RandomTools.Mix(unchecked((uint)randomSeed));
        var sample = (hash & 0x00ffffffu) / 16777216f;
        return sample < unlistedCellOccupancy;
    }

    private void ApplyDeterministicVariation(
        IslandGenerationSettings settings,
        int islandSeed)
    {
        if (parameterVariation == null || !parameterVariation.Enabled)
        {
            return;
        }

        var random = new System.Random(unchecked(islandSeed * 1664525 + 1013904223));
        settings.MaximumHeightMetres *= Scale(
            random,
            parameterVariation.MaximumHeightVariation);
        settings.WaterRatio += Signed(random) * parameterVariation.WaterRatioVariation;
        settings.InlandSlopeMultiplier *= Scale(random, parameterVariation.SlopeVariation);
        settings.CoastalSlopeMultiplier *= Scale(random, parameterVariation.SlopeVariation);
        settings.ContinentalNoiseFrequency *= Scale(
            random,
            parameterVariation.NoiseFrequencyVariation);
        settings.DetailNoiseFrequency *= Scale(
            random,
            parameterVariation.NoiseFrequencyVariation);
        settings.ContinentalNoiseStrength *= Scale(
            random,
            parameterVariation.NoiseStrengthVariation);
        settings.DetailNoiseStrength *= Scale(
            random,
            parameterVariation.NoiseStrengthVariation);
        settings.LandMassOffset += Signed(random)
            * parameterVariation.LandMassOffsetVariation;
        settings.HydraulicErosionStrength *= Scale(
            random,
            parameterVariation.ErosionVariation);
        settings.SedimentDepositionStrength *= Scale(
            random,
            parameterVariation.ErosionVariation);
    }

    private static float Scale(System.Random random, float variation)
    {
        return 1f + Signed(random) * Mathf.Clamp01(variation);
    }

    private static float Signed(System.Random random)
    {
        return (float)random.NextDouble() * 2f - 1f;
    }

    private void OnValidate()
    {
        unlistedCellOccupancy = Mathf.Clamp01(unlistedCellOccupancy);
        ValidateFixedIslands();
    }

    private void ValidateFixedIslands()
    {
        var occupied = new HashSet<Vector2Int>();
        foreach (var fixedIsland in fixedIslands)
        {
            if (fixedIsland != null && !occupied.Add(fixedIsland.GridPosition))
            {
                throw new InvalidOperationException(
                    $"Island grid cell {fixedIsland.GridPosition} is defined more than once.");
            }
        }
    }
}
